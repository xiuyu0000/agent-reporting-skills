export const CLI_IO_ERROR_CODES = [
  "PATH_INVALID",
  "PATH_ESCAPE",
  "SYMLINK_REJECTED",
  "PORTABLE_PATH_COLLISION",
  "CROSS_DEVICE_TRANSACTION",
  "TARGET_EXISTS",
  "REPLACE_IDENTITY_MISMATCH",
  "STAGED_CONTENT_INVALID",
  "TRANSACTION_MANIFEST_INVALID",
  "TRANSACTION_OWNER_UNKNOWN",
  "TRANSACTION_DIGEST_MISMATCH",
  "TRANSACTION_RECOVERY_BLOCKED",
  "IO_OPERATION_FAILED",
] as const;

export type CliIoErrorCode = (typeof CLI_IO_ERROR_CODES)[number];

export interface CliIoError {
  code: CliIoErrorCode;
  path: string;
  message: string;
  hint: string;
}

export type CliIoResult<T> =
  | { ok: true; value: T }
  | {
      ok: false;
      mutated: false;
      recoveryRequired: false;
      errors: readonly CliIoError[];
    }
  | {
      ok: false;
      mutated: true;
      recoveryRequired: true;
      errors: readonly CliIoError[];
    };

