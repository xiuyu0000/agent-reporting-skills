function normalizeErrorPath(path: string): string {
  if (typeof path !== "string" || !path.startsWith("/") || path.includes("\0")) return "/";
  return path;
}

export function cliIoError(code: CliIoErrorCode, path: string): CliIoError {
  const [message, hint] = ERROR_TEXT[code];
  return Object.freeze({ code, path: normalizeErrorPath(path), message, hint });
}

export function cliIoSuccess<T>(value: T): CliIoResult<T> {
  return { ok: true, value };
}

function compareErrors(left: CliIoError, right: CliIoError): number {
  if (left.path !== right.path) return left.path < right.path ? -1 : 1;
  if (left.code !== right.code) return left.code < right.code ? -1 : 1;
  return 0;
}

export function cliIoFailure<T = never>(
  errors: readonly CliIoError[],
  uncertain = false,
): CliIoResult<T> {
  const stableErrors = Object.freeze([...errors].sort(compareErrors));
  if (uncertain) {
    return { ok: false, mutated: true, recoveryRequired: true, errors: stableErrors };
  }
  return { ok: false, mutated: false, recoveryRequired: false, errors: stableErrors };
}

export function isCliIoErrorCode(value: unknown): value is CliIoErrorCode {
  return typeof value === "string" && (CLI_IO_ERROR_CODES as readonly string[]).includes(value);
}
